import express from 'express';
import { initialPrompts } from '../data/mockDatabase.js';

const router = express.Router();
let prompts = [...initialPrompts];

// GET /api/prompts
router.get('/', (req, res) => {
  res.json({ success: true, count: prompts.length, prompts });
});

// GET /api/prompts/:id
router.get('/:id', (req, res) => {
  const prompt = prompts.find(p => p.id === req.params.id);
  if (!prompt) return res.status(404).json({ success: false, error: 'Prompt not found' });
  res.json({ success: true, prompt });
});

// POST /api/prompts
router.post('/', (req, res) => {
  const { title, category, template, variables, sampleInputs } = req.body;
  if (!title || !template) {
    return res.status(400).json({ success: false, error: 'Title and template are required' });
  }

  // Detect variables matching {{var_name}}
  const detectedVariables = variables || Array.from(template.matchAll(/\{\{([^}]+)\}\}/g)).map(m => m[1].trim());

  const newPrompt = {
    id: `prompt-${Date.now()}`,
    title,
    category: category || 'Custom',
    version: 'v1.0',
    variables: [...new Set(detectedVariables)],
    template,
    sampleInputs: sampleInputs || {},
    performanceScore: 92,
    latency: '450ms'
  };

  prompts.push(newPrompt);
  res.status(201).json({ success: true, prompt: newPrompt });
});

// POST /api/prompts/substitute - Replace {{variable}} with provided values
router.post('/substitute', (req, res) => {
  const { template, values } = req.body;
  if (!template) {
    return res.status(400).json({ success: false, error: 'template string is required' });
  }

  const inputValues = values || {};
  let compiledPrompt = template;

  for (const [key, val] of Object.entries(inputValues)) {
    const regex = new RegExp(`\\{\\{\\s*${key}\\s*\\}\\}`, 'g');
    compiledPrompt = compiledPrompt.replace(regex, val);
  }

  // Estimated tokens (approx 4 chars per token)
  const estimatedTokens = Math.ceil(compiledPrompt.length / 4);

  res.json({
    success: true,
    compiledPrompt,
    estimatedTokens,
    missingVariables: Array.from(compiledPrompt.matchAll(/\{\{([^}]+)\}\}/g)).map(m => m[1].trim())
  });
});

// POST /api/prompts/benchmark - Side-by-side multi-model comparison matrix
router.post('/benchmark', (req, res) => {
  const { promptText, targetModels } = req.body;
  const prompt = promptText || "Analyze system concurrency risks for high-throughput WebSocket gateways.";
  const models = targetModels && targetModels.length > 0 ? targetModels : [
    "Gemini 2.0 Flash",
    "Claude 3.7 Sonnet",
    "GPT-4o",
    "DeepSeek R1"
  ];

  const modelSpecs = {
    "Gemini 2.0 Flash": { baseLatency: 280, costPer1k: 0.0001, reasoningScore: 95, color: "#4285F4" },
    "Claude 3.7 Sonnet": { baseLatency: 520, costPer1k: 0.003, reasoningScore: 97, color: "#D97706" },
    "GPT-4o": { baseLatency: 410, costPer1k: 0.0025, reasoningScore: 94, color: "#10A37F" },
    "DeepSeek R1": { baseLatency: 680, costPer1k: 0.0005, reasoningScore: 98, color: "#6366F1" }
  };

  const benchmarkResults = models.map(modelName => {
    const spec = modelSpecs[modelName] || { baseLatency: 450, costPer1k: 0.002, reasoningScore: 90, color: "#8B5CF6" };
    const latency = spec.baseLatency + Math.floor(Math.random() * 80) - 40;
    const tokens = Math.floor(Math.random() * 200) + 350;
    const cost = (tokens / 1000 * spec.costPer1k).toFixed(5);

    return {
      model: modelName,
      color: spec.color,
      latencyMs: latency,
      tokensUsed: tokens,
      costEstimate: `$${cost}`,
      reasoningScore: spec.reasoningScore,
      outputSummary: `High-fidelity analysis generated by ${modelName}: Evaluated socket descriptor limits, OS epoll/kqueue bottlenecks, and backpressure buffer thresholds.`
    };
  });

  res.json({
    success: true,
    promptLength: prompt.length,
    results: benchmarkResults
  });
});

export default router;
